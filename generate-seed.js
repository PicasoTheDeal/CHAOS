function sha512(message) {
  return crypto.createHash('sha512').update(message).digest('hex');
}

function generateRandomPool() {
  let pool = '';
  for (let i = 0; i < 256; i++) {
    pool += Math.floor(Math.random() * 10);
  }
  return pool;
}

